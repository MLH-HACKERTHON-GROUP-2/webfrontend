import test from 'node:test';
import assert from 'node:assert/strict';
import { graphql } from 'graphql';
import { createSimulation, schema } from './engine.mjs';
function setup() {
  let time = Date.parse('2026-10-31T08:00:00Z');
  const engine = createSimulation({ seedWorkspace: true, now: () => time });
  const run = (source, variableValues = {}, accessToken = '') => graphql({ schema, source, variableValues, rootValue: engine.root, fieldResolver: engine.fieldResolver, contextValue: { accessToken } });
  const login = async identifier => (await run('mutation($id:String!){verifyOtp(input:{identifier:$id,otp:"000000"}){accessToken}}', { id: identifier })).data.verifyOtp.accessToken;
  const action = (kind, input, token) => run('mutation($kind:WorkspaceAction!,$input:JSON!){workspaceAction(kind:$kind,input:$input)}', { kind, input }, token);
  const view = async token => structuredClone((await run('{myWorkspace}', {}, token)).data.myWorkspace);
  return { run, login, action, view, advance: n => { time += n; } };
}
const code = result => result.errors?.[0]?.extensions?.code;
test('normal workspace authorizes roles and shares server appointments across sessions', async () => {
  const { login, action, view, run } = setup();
  const doc = await login('doctor@emerald.care'), ph = await login('pharmacy@emerald.care'), patient = await login('patient@emerald.care');
  assert.equal(code(await run('{myWorkspace}')), 'UNAUTHENTICATED');
  assert.equal((await view(doc)).patients.length, 8);
  assert.equal((await view(ph)).patients.length, 0);
  assert.equal((await view(patient)).patients.length, 1);
  assert.equal(code(await action('ADD_MEDICINE', {}, doc)), 'FORBIDDEN');
  assert.equal(code(await action('START_VISIT', { patientId: 'PT-1001' }, ph)), 'FORBIDDEN');
  assert.equal(code(await action('ADD_DIAGNOSIS', { patientId: 'PT-1001', name: 'Test', notes: 'Test' }, doc)), 'SESSION_NOT_ACTIVE');
  const input = { patientId: 'PT-1001', date: '2026-11-02', time: '12:00', type: 'Consultation', reason: 'Shared appointment' };
  assert.ok((await action('ADD_APPOINTMENT', input, doc)).data);
  assert.equal(code(await action('ADD_APPOINTMENT', { ...input, time: '12:15' }, doc)), 'APPOINTMENT_CONFLICT');
  const secondLogin = await login('doctor@emerald.care');
  assert.ok((await view(secondLogin)).appointments.some(a => a.reason === input.reason));
  assert.ok((await view(patient)).appointments.some(a => a.reason === input.reason));
});
test('patients can book for themselves with a listed provider, see their booking and cancel it', async () => {
  const { login, action, view } = setup();
  const patient = await login('patient@emerald.care');
  const doctor = await login('doctor@emerald.care');
  const patientWorkspace = await view(patient);
  assert.equal(patientWorkspace.appointmentProviders.length, 1);
  assert.equal(patientWorkspace.appointmentProviders[0].hospitalName, 'Emerald Medical Centre');
  const item = { patientId: 'PT-1001', doctorId: patientWorkspace.appointmentProviders[0].id, date: '2026-11-04', time: '10:00', type: 'Consultation', reason: 'Patient requested a checkup' };
  assert.ok((await action('ADD_APPOINTMENT', item, patient)).data);
  const booking = (await view(patient)).appointments.find(a => a.reason === item.reason);
  assert.equal(booking.doctorName, 'Dr. Sarah Mitchell');
  assert.ok((await view(doctor)).appointments.some(a => a.id === booking.id));
  const otherPatient = await login('avery.patient@emerald.care');
  assert.ok(!(await view(otherPatient)).appointments.some(a => a.id === booking.id));
  assert.equal(code(await action('ADD_APPOINTMENT', { ...item, patientId: 'PT-1009', time: '10:45' }, patient)), 'FORBIDDEN');
  assert.equal(code(await action('UPDATE_APPOINTMENT', { id: booking.id, status: 'Completed' }, patient)), 'FORBIDDEN');
  assert.ok((await action('UPDATE_APPOINTMENT', { id: booking.id, status: 'Cancelled' }, patient)).data);
  assert.equal((await view(doctor)).appointments.find(a => a.id === booking.id).status, 'Cancelled');
});
test('normal consultation finalization releases prescriptions, charges once and completes appointment', async () => {
  const { login, action, view, run } = setup();
  const doc = await login('doctor@emerald.care'), patient = await login('patient@emerald.care');
  await action('START_VISIT', { patientId: 'PT-1001', appointmentId: 'APT-201' }, doc);
  const session = (await view(doc)).sessions.find(s => s.status === 'ACTIVE');
  await action('SAVE_VITALS', { patientId: 'PT-1001', vitals: { heartRate: 74 } }, doc);
  await action('ADD_DIAGNOSIS', { patientId: 'PT-1001', name: 'Shared diagnosis', code: 'Z00', notes: 'Shared assessment' }, doc);
  await action('SAVE_NOTE', { patientId: 'PT-1001', text: 'Shared note' }, doc);
  await action('ADD_PRESCRIPTION', { patientId: 'PT-1001', medicineId: 'MED-003', quantity: 10, dosage: 'Test instructions', duration: 'Test duration' }, doc);
  assert.equal((await view(patient)).sessions.find(s => s.id === session.id).vitals.heartRate, 74);
  assert.ok((await view(patient)).notes.some(n => n.text === 'Shared note'));
  const before = (await view(patient)).wallet;
  const finalize = 'mutation($id:ID!){finalizeSession(sessionId:$id){status}}';
  assert.equal((await run(finalize, { id: session.id }, doc)).data.finalizeSession.status, 'FINALIZED');
  assert.equal((await view(patient)).wallet, before - 150);
  assert.equal((await view(doc)).appointments.find(a => a.id === 'APT-201').status, 'Completed');
  assert.equal(code(await run(finalize, { id: session.id }, doc)), 'SESSION_NOT_ACTIVE');
  assert.equal((await view(patient)).wallet, before - 150);
  assert.equal(code(await action('SAVE_NOTE', { patientId: 'PT-1001', text: 'Closed visit' }, doc)), 'SESSION_NOT_ACTIVE');
});
test('pharmacy consent gates patient reads, dispensing updates stock and wallets once, revocation removes access', async () => {
  const { login, action, view, run } = setup();
  const ph = await login('pharmacy@emerald.care'), patient = await login('patient@emerald.care');
  const seedRx = 'RX-3001';
  assert.equal(code(await action('DISPENSE', { id: seedRx }, ph)), 'FORBIDDEN');
  const qr = (await run('mutation{createLoginQr{token connection{id}}}', {}, ph)).data.createLoginQr;
  await run('mutation($token:String!){approveLoginQr(token:$token){status}}', { token: qr.token }, patient);
  const before = await view(ph), balance = (await view(patient)).wallet;
  assert.equal(before.patients.length, 1);
  assert.equal(before.patients[0].id, 'PT-1001');
  assert.equal((await action('DISPENSE', { id: seedRx }, ph)).data.workspaceAction.prescriptions.find(r => r.id === seedRx).status, 'Dispensed');
  const after = await view(ph);
  assert.equal(after.medicines.find(m => m.id === 'MED-001').stock, before.medicines.find(m => m.id === 'MED-001').stock - 30);
  assert.equal(after.wallet, 75);
  assert.equal((await view(patient)).wallet, balance - 75);
  assert.equal(code(await action('DISPENSE', { id: seedRx }, ph)), 'ALREADY_DISPENSED');
  assert.equal((await view(patient)).wallet, balance - 75);
  await run('mutation($id:ID!){revokePairing(id:$id){status}}', { id: qr.connection.id }, patient);
  assert.equal((await view(ph)).patients.length, 0);
  assert.equal((await view(ph)).prescriptions.length, 0);
  assert.equal(code(await action('DISPENSE', { id: seedRx }, ph)), 'FORBIDDEN');
});
test('failed stock checks do not charge; medicines and prices are scoped to each pharmacy', async () => {
  const { login, action, view, run } = setup();
  const sys = await login('system@emerald.care');
  await run('mutation{onboardPharmacy(input:{name:"Other Pharmacy",address:"Other",userName:"Other Pharmacist",userIdentifier:"other@pharmacy.test"}){id}}', {}, sys);
  const ph = await login('other@pharmacy.test'), patient = await login('patient@emerald.care');
  const qr = (await run('mutation{createLoginQr{token}}', {}, ph)).data.createLoginQr;
  await run('mutation($token:String!){approveLoginQr(token:$token){status}}', { token: qr.token }, patient);
  const balance = (await view(patient)).wallet;
  assert.equal(code(await action('DISPENSE', { id: 'RX-3001' }, ph)), 'INSUFFICIENT_STOCK');
  assert.equal((await view(patient)).wallet, balance);
  await action('ADD_MEDICINE', { name: 'Amlodipine', generic: 'Amlodipine', category: 'Cardiovascular', strength: '5mg', stock: 35, threshold: 10, price: 2, expiry: '2028-12-31' }, ph);
  assert.ok((await action('DISPENSE', { id: 'RX-3001' }, ph)).data);
  assert.equal((await view(ph)).medicines.find(m => m.name === 'Amlodipine').stock, 5);
  assert.equal((await view(patient)).wallet, balance - 60);
  assert.equal((await view(await login('pharmacy@emerald.care'))).medicines.find(m => m.id === 'MED-001').stock, 240);
});
test('QR scan expiry removes pharmacy access and invalid clinical input has no partial effects', async () => {
  const { run, action, view, login, advance } = setup();
  const doc = await login('doctor@emerald.care'), ph = await login('pharmacy@emerald.care'), patient = await login('patient@emerald.care');
  const qr = (await run('mutation{generateQrToken{token}}', {}, patient)).data.generateQrToken;
  await action('VERIFY_PATIENT', { token: qr.token }, ph);
  assert.equal((await view(ph)).patients.length, 1);
  advance(120001);
  assert.equal((await view(ph)).patients.length, 0);
  assert.equal(code(await action('DISPENSE', { id: 'RX-3001' }, ph)), 'FORBIDDEN');
  assert.equal(code(await action('ADD_APPOINTMENT', { patientId: 'PT-1001', date: '2026-11-02', time: '08:90', reason: 'Invalid', type: 'Consultation' }, doc)), 'BAD_USER_INPUT');
  assert.equal(code(await action('START_VISIT', { patientId: 'PT-1001', appointmentId: 'not-owned' }, doc)), 'BAD_USER_INPUT');
  assert.equal((await view(doc)).sessions.filter(s => s.status === 'ACTIVE').length, 0);
  await action('START_VISIT', { patientId: 'PT-1001', appointmentId: 'APT-201' }, doc);
  const invalid = await action('ADD_PRESCRIPTION', { patientId: 'PT-1001', medicineId: 'MED-001', quantity: 5, dosage: 'Test', duration: '' }, doc);
  assert.equal(code(invalid), 'BAD_USER_INPUT');
  assert.equal((await view(doc)).prescriptions.filter(r => r.finalized === false).length, 0);
  assert.equal(code(await action('SAVE_VITALS', { patientId: 'PT-1001', vitals: { heartRate: 'invalid' } }, doc)), 'BAD_USER_INPUT');
});
