import { test, expect } from '@playwright/test';
import { createRequire } from 'node:module';
import jsQR from 'jsqr';
import { login, createPair, approve } from './helpers';
const { PNG } = createRequire(process.cwd() + '/package.json')('pngjs');
test('normal QR connection renders real QR, requires consent, rejects replay and clears revoked records', async ({ page: pharmacy, context }) => {
  await login(pharmacy, 'pharmacy@emerald.care');
  const link = await createPair(pharmacy);
  const src = await pharmacy.getByRole('img', { name: 'One-time login QR for patient pairing' }).getAttribute('src');
  const bitmap = PNG.sync.read(Buffer.from(src!.split(',')[1], 'base64'));
  expect(jsQR(new Uint8ClampedArray(bitmap.data), bitmap.width, bitmap.height)?.data).toBe(link);
  await expect(pharmacy.locator('.pairing-patient')).toHaveCount(0);
  const patient = await context.newPage();
  await patient.goto(link);
  await expect(patient).toHaveURL(/login/);
  await patient.getByLabel('Email address', { exact: true }).fill('avery.patient@emerald.care');
  await patient.getByRole('button', { name: 'Request code', exact: true }).click();
  await patient.getByLabel('One-time code', { exact: true }).fill('000000');
  await patient.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(patient).toHaveURL(/portal/);
  await expect(patient.getByLabel('Staff login QR or pairing link')).not.toHaveValue('');
  await patient.getByRole('button', { name: 'Review connection', exact: true }).click();
  await expect(patient.getByRole('region', { name: 'Approve patient connection' })).toContainText('Taylor Jacobs');
  await expect(pharmacy.locator('.pairing-patient')).toHaveCount(0);
  await patient.getByRole('button', { name: 'Approve connection', exact: true }).click();
  await expect(pharmacy.locator('.pairing-patient')).toContainText('Avery Patel');
  await expect(pharmacy.getByLabel('One-time pairing link')).toHaveCount(0);
  await patient.getByLabel('Staff login QR or pairing link').fill(link);
  await patient.getByRole('button', { name: 'Review connection', exact: true }).click();
  await expect(patient.locator('.simulation-error')).toContainText('already been used');
  await pharmacy.getByRole('link', { name: 'View patient records', exact: true }).click();
  await expect(pharmacy.locator('.record-detail')).toContainText('Avery Patel');
  await patient.locator('.pairing-connection-row').filter({ hasText: 'Taylor Jacobs' }).getByRole('button', { name: 'Disconnect', exact: true }).click();
  await expect(pharmacy.getByRole('heading', { name: 'No patient connected', exact: true })).toBeVisible();
  await pharmacy.goto('/pharmacy');
  await expect(pharmacy.locator('.pairing-patient')).toHaveCount(0);
  await patient.close();
});
test('patient mobile camera scans staff QR, can decline then approve, and releases the stream', async ({ page: doctor, context }) => {
  await login(doctor);
  await doctor.goto('/connections');
  const link = await createPair(doctor);
  const QRCode = createRequire(process.cwd() + '/package.json')('qrcode');
  const src = await QRCode.toDataURL(link, { width: 300, margin: 4 });
  const patient = await context.newPage();
  await patient.setViewportSize({ width: 390, height: 844 });
  await patient.addInitScript(({ src }) => {
    Object.defineProperty(navigator, 'mediaDevices', { value: { getUserMedia: async () => {
      const canvas = document.createElement('canvas'); canvas.width = 640; canvas.height = 480;
      const ctx = canvas.getContext('2d')!, img = new Image(); img.src = src; await img.decode();
      const draw = () => { ctx.fillStyle = 'white'; ctx.fillRect(0, 0, 640, 480); ctx.drawImage(img, 170, 90, 300, 300); };
      draw(); const stream = canvas.captureStream(10); (window as any).__qrStream = stream;
      const timer = setInterval(draw, 100); stream.getTracks()[0].addEventListener('ended', () => clearInterval(timer)); return stream;
    } } });
  }, { src });
  await login(patient, 'avery.patient@emerald.care');
  await patient.getByRole('button', { name: 'Scan login QR', exact: true }).click();
  await patient.getByRole('button', { name: 'Enable camera', exact: true }).click();
  await expect(patient.getByRole('region', { name: 'Approve patient connection' })).toBeVisible();
  expect(await patient.evaluate(() => (window as any).__qrStream.getTracks().every((track: MediaStreamTrack) => track.readyState === 'ended'))).toBe(true);
  await patient.getByRole('button', { name: 'Decline', exact: true }).click();
  await expect(doctor.locator('.pairing-patient')).toHaveCount(0);
  await approve(patient, link);
  await expect(doctor.locator('.pairing-patient')).toContainText('Avery Patel');
  expect(await patient.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await doctor.getByRole('link', { name: 'Open consultation', exact: true }).click();
  await expect(doctor.getByLabel('Select patient for consultation')).toHaveValue('PT-1009');
  await patient.screenshot({ path: 'test-results/actual-patient-mobile.png', fullPage: true });
  await doctor.screenshot({ path: 'test-results/actual-doctor-session.png', fullPage: true });
  await patient.locator('.pairing-connection-row').filter({ hasText: 'Dr. Sarah Mitchell' }).getByRole('button', { name: 'Disconnect', exact: true }).click();
  await patient.close();
});
